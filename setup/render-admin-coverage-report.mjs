import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(here, '..')
const matrixPath = resolve(here, 'coverage-matrix.json')
const reportPath = resolve(repoRoot, 'docs/admin-e2e-coverage.md')
const statuses = ['required-e2e', 'smoke-only', 'inventory-only', 'deprecated']

function cell(value) {
  if (value === null || value === undefined || value === '') return ''
  return String(value).replace(/\s+/g, ' ').replace(/\|/g, '\\|')
}

function assertSummary(assertion = {}) {
  return ['text', 'selector', 'apiWait'].filter((key) => assertion[key]).join(', ')
}

const matrix = JSON.parse(readFileSync(matrixPath, 'utf8'))
const lines = [
  '# Admin E2E Coverage',
  '',
  '_Generated by `pnpm admin:coverage:report` from `setup/coverage-matrix.json`._',
  '',
  '## Summary',
  '',
  '| Status | Count |',
  '|---|---:|',
  ...statuses.map((status) => `| ${status} | ${matrix.filter((entry) => entry.status === status).length} |`),
  `| total | ${matrix.length} |`,
  '',
  '## Routes',
  '',
  '| Nav | Component | Action | Status | Path | Assert |',
  '|---|---|---|---|---|---|',
  ...matrix.map((entry) =>
    `| ${cell(entry.nav)} | ${cell(entry.component)} | ${cell(entry.action)} | ${cell(entry.status)} | ${cell(entry.path)} | ${cell(assertSummary(entry.assert))} |`
  )
]

mkdirSync(dirname(reportPath), { recursive: true })
writeFileSync(reportPath, `${lines.join('\n')}\n`)
console.log(`admin coverage report: ${reportPath}`)
